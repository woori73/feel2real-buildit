#!/usr/bin/env bash
#
# Worktree별 독립 MySQL 컨테이너/DB를 관리한다.
#
# 사용:
#   ./scripts/worktree-db.sh up      # .envrc.local 생성 + MySQL 시작
#   ./scripts/worktree-db.sh status  # 현재 worktree DB 설정/컨테이너 상태 출력
#   ./scripts/worktree-db.sh down    # 컨테이너 중지/삭제, volume 보존
#   ./scripts/worktree-db.sh reset   # 컨테이너 + volume 삭제 (DB 초기화)
#   ./scripts/worktree-db.sh env     # direnv에 로드될 env 출력
#
# 참고:
#   MYSQL_ROOT_PASSWORD, MYSQL_USER, MYSQL_PASSWORD가 없으면 로컬 개발 기본값을 사용한다.
#   생성되는 .envrc.local은 .gitignore 대상이다.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_FILE="${HOME}/.config/f2r/env"
DOTENV_FILE="${ROOT}/.env"
LOCAL_ENV="${ROOT}/.envrc.local"
COMPOSE_FILE="${ROOT}/docker-compose.worktree.yaml"
COMMAND="${1:-up}"

load_shared_env() {
  if [[ -f "${DOTENV_FILE}" ]]; then
    set -a
    # shellcheck disable=SC1090
    source "${DOTENV_FILE}"
    set +a
  fi
  if [[ -f "${ENV_FILE}" ]]; then
    set -a
    # shellcheck disable=SC1090
    source "${ENV_FILE}"
    set +a
  fi
}

current_branch() {
  git -C "${ROOT}" branch --show-current 2>/dev/null || true
}

slugify() {
  printf '%s' "$1" \
    | tr '[:upper:]' '[:lower:]' \
    | sed -E 's#[^a-z0-9]+#_#g; s#^_+##; s#_+$##; s#_+#_#g' \
    | cut -c 1-48
}


ensure_not_main_branch() {
  local branch
  branch="$(current_branch)"
  if [[ "${branch}" == "main" ]]; then
    echo "ERROR: scripts/worktree-db.sh is for feature worktrees, not main." >&2
    echo "main should use application-local.yaml defaults (localhost:3308/f2r_db)." >&2
    echo "If a generated .envrc.local exists in main, remove it." >&2
    exit 2
  fi
}

make_slug() {
  local branch slug
  branch="$(current_branch)"
  if [[ -z "${branch}" ]]; then
    branch="$(basename "${ROOT}")"
  fi
  slug="$(slugify "${branch}")"
  if [[ -z "${slug}" ]]; then
    slug="worktree"
  fi
  printf '%s' "${slug}"
}

port_in_use() {
  local port="$1"
  lsof -nP -iTCP:"${port}" -sTCP:LISTEN >/dev/null 2>&1
}

make_port() {
  local slug hash port attempts
  slug="$1"
  # 티어 브랜치는 고정 예약 DB 포트 (main=3308은 이 스크립트 대상 아님).
  # feature 워크트리는 해시 포트(34000~35999). 상세: docs/WORKFLOW.md §1
  case "${slug}" in
    dev) printf '3309'; return ;;
    stg) printf '3310'; return ;;
  esac
  hash="$(printf '%s' "${slug}" | cksum | awk '{print $1}')"
  port=$((34000 + (hash % 2000)))
  attempts=0
  while port_in_use "${port}" && [[ ${attempts} -lt 200 ]]; do
    port=$((port + 1))
    attempts=$((attempts + 1))
    if [[ ${port} -gt 35999 ]]; then
      port=34000
    fi
  done
  printf '%s' "${port}"
}

make_server_port() {
  # HTTP 서버 포트도 티어/워크트리별로 분리해 동시 실행 시 8080 충돌 방지.
  # main=8080(대상 아님), dev=8081, stg=8082, feature=8100~8999 해시.
  local slug hash port attempts
  slug="$1"
  case "${slug}" in
    dev) printf '8081'; return ;;
    stg) printf '8082'; return ;;
  esac
  hash="$(printf '%s' "${slug}" | cksum | awk '{print $1}')"
  port=$((8100 + (hash % 900)))
  attempts=0
  while port_in_use "${port}" && [[ ${attempts} -lt 200 ]]; do
    port=$((port + 1))
    attempts=$((attempts + 1))
    if [[ ${port} -gt 8999 ]]; then
      port=8100
    fi
  done
  printf '%s' "${port}"
}

write_envrc_local() {
  ensure_not_main_branch
  local slug port server_port db_name container volume
  slug="$(make_slug)"
  port="$(make_port "${slug}")"
  server_port="$(make_server_port "${slug}")"
  db_name="f2r_${slug}"
  container="f2r_mysql_${slug}"
  volume="f2r_mysql_${slug}"

  if [[ -f "${LOCAL_ENV}" ]]; then
    echo "exists: ${LOCAL_ENV}"
    return
  fi

  {
    cat <<EOV
# Generated by scripts/worktree-db.sh for this git worktree.
# This file is intentionally gitignored.
export F2R_WORKTREE_SLUG="${slug}"
export F2R_DB_PORT="${port}"
export F2R_DB_NAME="${db_name}"
export F2R_DB_CONTAINER="${container}"
export F2R_DB_VOLUME="${volume}"
export SERVER_PORT="${server_port}"
EOV
    case "${slug}" in
      dev|stg)
        # dev/stg는 datasource·flyway를 전용 프로필(config/application-${slug}.yaml)이,
        # 프로필 활성(active: local,${slug})은 해당 브랜치 application.yaml이 담당한다.
        # → IntelliJ 그냥 Run / 터미널 둘 다 자동. 여기선 추가 env 불필요(SERVER_PORT는 위에서 설정).
        :
        ;;
      *)
        # feature 워크트리는 브랜치마다 동적 DB라 datasource를 env로 주입한다 (local 프로필).
        cat <<EOV
export SPRING_DATASOURCE_URL="jdbc:mysql://localhost:${port}/${db_name}?useUnicode=true&characterEncoding=UTF-8&connectionCollation=utf8mb4_unicode_ci"
export SPRING_DATASOURCE_USERNAME="\${MYSQL_USER:-f2r_user}"
export SPRING_DATASOURCE_PASSWORD="\${MYSQL_PASSWORD:-f2r_password}"
EOV
        ;;
    esac
  } > "${LOCAL_ENV}"
  echo "created: ${LOCAL_ENV}"
}

load_local_env() {
  if [[ ! -f "${LOCAL_ENV}" ]]; then
    write_envrc_local
  fi
  # shellcheck disable=SC1090
  source "${LOCAL_ENV}"
}

require_mysql_env() {
  export MYSQL_ROOT_PASSWORD="${MYSQL_ROOT_PASSWORD:-f2r_root_password}"
  export MYSQL_USER="${MYSQL_USER:-f2r_user}"
  export MYSQL_PASSWORD="${MYSQL_PASSWORD:-f2r_password}"
}

compose() {
  docker compose \
    --project-name "f2r_${F2R_WORKTREE_SLUG}" \
    -f "${COMPOSE_FILE}" \
    "$@"
}

wait_until_healthy() {
  local status attempts
  attempts=0
  while [[ ${attempts} -lt 60 ]]; do
    status="$(docker inspect -f '{{if .State.Health}}{{.State.Health.Status}}{{else}}no-healthcheck{{end}}' "${F2R_DB_CONTAINER}" 2>/dev/null || true)"
    if [[ "${status}" == "healthy" || "${status}" == "no-healthcheck" ]]; then
      return 0
    fi
    if [[ "${status}" == "unhealthy" ]]; then
      echo "WARN: ${F2R_DB_CONTAINER} healthcheck is unhealthy." >&2
      return 1
    fi
    sleep 1
    attempts=$((attempts + 1))
  done
  echo "WARN: ${F2R_DB_CONTAINER} did not become healthy within 60s." >&2
  return 1
}

print_env() {
  load_shared_env
  load_local_env
  cat <<EOT
F2R_WORKTREE_SLUG=${F2R_WORKTREE_SLUG}
F2R_DB_PORT=${F2R_DB_PORT}
F2R_DB_NAME=${F2R_DB_NAME}
F2R_DB_CONTAINER=${F2R_DB_CONTAINER}
F2R_DB_VOLUME=${F2R_DB_VOLUME}
SPRING_DATASOURCE_URL=${SPRING_DATASOURCE_URL}
EOT
}

case "${COMMAND}" in
  init)
    write_envrc_local
    ;;
  up)
    load_shared_env
    load_local_env
    require_mysql_env
    compose up -d
    wait_until_healthy || true
    echo
    echo "Worktree DB is ready: ${F2R_DB_CONTAINER}"
    echo "  port: ${F2R_DB_PORT}"
    echo "  db:   ${F2R_DB_NAME}"
    echo
    echo "Next:"
    echo "  direnv allow ."
    echo "  direnv exec . ./gradlew bootRun"
    ;;
  down)
    load_shared_env
    load_local_env
    require_mysql_env
    compose down
    ;;
  reset)
    load_shared_env
    load_local_env
    require_mysql_env
    compose down -v
    ;;
  status)
    load_shared_env
    load_local_env
    print_env
    echo
    if ! docker ps -a --filter "name=${F2R_DB_CONTAINER}" --format 'table {{.Names}}\t{{.Status}}\t{{.Ports}}'; then
      echo "WARN: Docker daemon에 접근할 수 없습니다. Docker Desktop이 켜져 있는지 확인하세요." >&2
    fi
    ;;
  env)
    print_env
    ;;
  *)
    echo "Usage: $0 {init|up|down|reset|status|env}" >&2
    exit 2
    ;;
esac
