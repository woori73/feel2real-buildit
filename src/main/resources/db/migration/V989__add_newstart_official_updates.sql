CREATE TABLE newstart_official_updates (
    update_id            BIGINT        NOT NULL AUTO_INCREMENT,
    source_type          VARCHAR(30)   NOT NULL,
    source_name          VARCHAR(100)  NOT NULL,
    title                VARCHAR(200)  NOT NULL,
    summary              TEXT          NOT NULL,
    original_url         VARCHAR(500),
    official_document_id VARCHAR(200),
    published_at         DATETIME(6),
    effective_from       DATETIME(6),
    effective_to         DATETIME(6),
    category             VARCHAR(30)   NOT NULL,
    review_status        VARCHAR(20)   NOT NULL DEFAULT 'REVIEW',
    featured             BOOLEAN       NOT NULL DEFAULT FALSE,
    dedup_key            VARCHAR(512)  NOT NULL,
    reviewed_by          VARCHAR(100),
    reviewed_at          DATETIME(6),
    created_at           DATETIME(6)   NOT NULL,
    updated_at           DATETIME(6)   NOT NULL,
    PRIMARY KEY (update_id),
    UNIQUE KEY uk_newstart_official_updates_dedup (dedup_key),
    INDEX idx_newstart_updates_public_feed (review_status, featured, published_at),
    INDEX idx_newstart_updates_source (review_status, source_type)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
