CREATE TABLE choonggi_posts (
  post_id BIGINT NOT NULL AUTO_INCREMENT,
  episode_code VARCHAR(30) NOT NULL,
  title VARCHAR(120) NOT NULL,
  slug VARCHAR(140) NOT NULL,
  body TEXT NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
  published_at DATETIME(6) NULL,
  deleted_at DATETIME(6) NULL,
  created_at DATETIME(6) NOT NULL,
  updated_at DATETIME(6) NOT NULL,
  created_by VARCHAR(50) NULL,
  updated_by VARCHAR(50) NULL,
  PRIMARY KEY (post_id),
  UNIQUE KEY uq_choonggi_posts_slug (slug),
  KEY idx_choonggi_posts_public (status, deleted_at, published_at)
);

CREATE TABLE choonggi_media (
  media_id BIGINT NOT NULL AUTO_INCREMENT,
  post_id BIGINT NOT NULL,
  storage_key VARCHAR(700) NOT NULL,
  media_type VARCHAR(10) NOT NULL,
  content_type VARCHAR(100) NOT NULL,
  original_filename VARCHAR(255) NOT NULL,
  size_bytes BIGINT NOT NULL,
  width INT NULL,
  height INT NULL,
  duration_ms BIGINT NULL,
  sort_order INT NOT NULL DEFAULT 0,
  cover_media BOOLEAN NOT NULL DEFAULT FALSE,
  deleted_at DATETIME(6) NULL,
  created_at DATETIME(6) NOT NULL,
  updated_at DATETIME(6) NOT NULL,
  created_by VARCHAR(50) NULL,
  updated_by VARCHAR(50) NULL,
  PRIMARY KEY (media_id),
  CONSTRAINT fk_choonggi_media_post FOREIGN KEY (post_id) REFERENCES choonggi_posts(post_id),
  KEY idx_choonggi_media_post_order (post_id, deleted_at, sort_order)
);
